/**
 * 生成 examples/ 下的示例模型：
 *   • gear.obj   —— 齿轮（带齿圆盘，OBJ）
 *   • torus.stl  —— 圆环（二进制 STL）
 *   • box.step   —— 立方体（AP214 STEP）
 *
 * 运行：node scripts/generate-examples.mjs
 */
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const examples = join(root, 'examples')

const round = (n, d = 6) => {
  const f = 10 ** d
  return Math.round(n * f) / f
}

// ─────────────────────────────────────────────────────────────────────────────
// 1) OBJ 齿轮（矩形齿圆盘，挤出成型）
// ─────────────────────────────────────────────────────────────────────────────
function generateGearObj() {
  const teeth = 12
  const outerR = 10
  const innerR = 6
  const height = 3
  const fullStep = (2 * Math.PI) / teeth

  const profile = []
  for (let i = 0; i < teeth; i++) {
    const base = i * fullStep
    const tipStart = base + fullStep * 0.2
    const tipEnd = base + fullStep * 0.8
    const nextBase = base + fullStep
    profile.push([innerR * Math.cos(base), innerR * Math.sin(base)])
    profile.push([outerR * Math.cos(tipStart), outerR * Math.sin(tipStart)])
    profile.push([outerR * Math.cos(tipEnd), outerR * Math.sin(tipEnd)])
    profile.push([innerR * Math.cos(nextBase), innerR * Math.sin(nextBase)])
  }
  const n = profile.length

  const lines = ['# gear example — generated by scripts/generate-examples.mjs', 'o gear']
  for (const [x, y] of profile) lines.push(`v ${round(x)} ${round(y)} 0`)
  for (const [x, y] of profile) lines.push(`v ${round(x)} ${round(y)} ${round(height)}`)

  // 底面三角扇（法线 -z）
  for (let i = 1; i + 1 < n; i++) lines.push(`f 1 ${i + 1} ${i + 2}`)
  // 顶面三角扇（法线 +z）
  for (let i = 1; i + 1 < n; i++) lines.push(`f ${n + 1} ${n + i + 1} ${n + i + 2}`)

  // 侧壁（法线向外）
  for (let i = 0; i < n; i++) {
    const j = (i + 1) % n
    const b0 = i + 1, b1 = j + 1
    const t0 = n + i + 1, t1 = n + j + 1
    lines.push(`f ${b0} ${t0} ${t1}`)
    lines.push(`f ${b0} ${t1} ${b1}`)
  }
  return lines.join('\n') + '\n'
}

// ─────────────────────────────────────────────────────────────────────────────
// 2) STL 圆环（二进制）
// ─────────────────────────────────────────────────────────────────────────────
function generateTorusStl() {
  const R = 8
  const r = 3
  const Nu = 48
  const Nv = 24

  const pts = (u, v) => {
    const x = (R + r * Math.cos(v)) * Math.cos(u)
    const y = (R + r * Math.cos(v)) * Math.sin(u)
    const z = r * Math.sin(v)
    return [x, y, z]
  }

  const triangles = []
  for (let i = 0; i < Nu; i++) {
    const u0 = (i / Nu) * 2 * Math.PI
    const u1 = ((i + 1) / Nu) * 2 * Math.PI
    for (let j = 0; j < Nv; j++) {
      const v0 = (j / Nv) * 2 * Math.PI
      const v1 = ((j + 1) / Nv) * 2 * Math.PI
      const a = pts(u0, v0)
      const b = pts(u1, v0)
      const c = pts(u1, v1)
      const d = pts(u0, v1)
      triangles.push([a, b, c])
      triangles.push([a, c, d])
    }
  }

  const header = Buffer.alloc(80, 0)
  header.write('torus example', 0, 'ascii')
  const count = triangles.length
  const buf = Buffer.alloc(84 + count * 50)
  header.copy(buf, 0)
  buf.writeUInt32LE(count, 80)
  let off = 84
  for (const [a, b, c] of triangles) {
    const u = [b[0] - a[0], b[1] - a[1], b[2] - a[2]]
    const v = [c[0] - a[0], c[1] - a[1], c[2] - a[2]]
    const nx = u[1] * v[2] - u[2] * v[1]
    const ny = u[2] * v[0] - u[0] * v[2]
    const nz = u[0] * v[1] - u[1] * v[0]
    const len = Math.hypot(nx, ny, nz) || 1
    buf.writeFloatLE(nx / len, off)
    buf.writeFloatLE(ny / len, off + 4)
    buf.writeFloatLE(nz / len, off + 8)
    let p = off + 12
    for (const v of [a, b, c]) {
      buf.writeFloatLE(v[0], p)
      buf.writeFloatLE(v[1], p + 4)
      buf.writeFloatLE(v[2], p + 8)
      p += 12
    }
    buf.writeUInt16LE(0, off + 48)
    off += 50
  }
  return buf
}

// ─────────────────────────────────────────────────────────────────────────────
// 3) STEP 立方体（AP214 MANIFOLD_SOLID_BREP，40×20×10）
// ─────────────────────────────────────────────────────────────────────────────
function generateBoxStep() {
  const w = 40, d = 20, h = 10
  const P = {
    1: [0, 0, 0], 2: [w, 0, 0], 3: [w, d, 0], 4: [0, d, 0],
    5: [0, 0, h], 6: [w, 0, h], 7: [w, d, h], 8: [0, d, h],
  }
  // 6 个面：法线 + 角点环（从外看逆时针）
  const faces = [
    { n: [0, 0, -1], loop: [1, 4, 3, 2] }, // bottom
    { n: [0, 0, 1], loop: [5, 6, 7, 8] },  // top
    { n: [0, -1, 0], loop: [1, 2, 6, 5] }, // front
    { n: [0, 1, 0], loop: [4, 8, 7, 3] },  // back
    { n: [-1, 0, 0], loop: [1, 5, 8, 4] }, // left
    { n: [1, 0, 0], loop: [2, 3, 7, 6] },  // right
  ]
  // 12 条边（canonical 方向：小点 → 大点）
  const edges = [
    [1, 2], [2, 3], [3, 4], [4, 1],
    [5, 6], [6, 7], [7, 8], [8, 5],
    [1, 5], [2, 6], [3, 7], [4, 8],
  ]

  let id = 0
  const next = () => ++id
  const S = []
  const emit = (s) => S.push(s)
  const fmt = (a) => a.map((x) => `${round(x)}.`).join(',')

  // 8 个点
  const pointId = {}
  for (const k of Object.keys(P)) {
    pointId[k] = next()
    emit(`#${pointId[k]}=CARTESIAN_POINT('',(${fmt(P[k])}));`)
  }

  // 12 条边
  const edgeCurveId = {}
  for (const [a, b] of edges) {
    const pa = P[a], pb = P[b]
    const vp1 = next()
    emit(`#${vp1}=VERTEX_POINT('',#${pointId[a]});`)
    const vp2 = next()
    emit(`#${vp2}=VERTEX_POINT('',#${pointId[b]});`)
    const dir = next()
    const dx = pb[0] - pa[0], dy = pb[1] - pa[1], dz = pb[2] - pa[2]
    emit(`#${dir}=DIRECTION('',(${fmt([dx, dy, dz])}));`)
    const vec = next()
    emit(`#${vec}=VECTOR('',#${dir},1.);`)
    const line = next()
    emit(`#${line}=LINE('',#${pointId[a]},#${vec});`)
    const ec = next()
    emit(`#${ec}=EDGE_CURVE('',#${vp1},#${vp2},#${line},.T.);`)
    edgeCurveId[`${a}-${b}`] = ec
  }

  // 6 个面
  const faceIds = []
  for (const face of faces) {
    const n = face.n
    const axisZ = next()
    emit(`#${axisZ}=DIRECTION('',(${fmt(n)}));`)
    // 参考方向：取一个与法线不共线的轴，再做叉积得到垂直方向
    const pick = Math.abs(n[0]) < 0.9 ? [1, 0, 0] : [0, 1, 0]
    const ref = [
      n[1] * pick[2] - n[2] * pick[1],
      n[2] * pick[0] - n[0] * pick[2],
      n[0] * pick[1] - n[1] * pick[0],
    ]
    const axisX = next()
    emit(`#${axisX}=DIRECTION('',(${fmt(ref)}));`)
    const axis = next()
    emit(`#${axis}=AXIS2_PLACEMENT_3D('',#${pointId[face.loop[0]]},#${axisZ},#${axisX});`)
    const plane = next()
    emit(`#${plane}=PLANE('',#${axis});`)

    const oriented = []
    for (let i = 0; i < 4; i++) {
      const a = face.loop[i]
      const b = face.loop[(i + 1) % 4]
      const canonical = edgeCurveId[`${a}-${b}`]
      const reverse = edgeCurveId[`${b}-${a}`]
      const ec = canonical ?? reverse
      const oe = next()
      emit(`#${oe}=ORIENTED_EDGE('',*,*,#${ec},${canonical ? '.T.' : '.F.'});`)
      oriented.push(oe)
    }
    const el = next()
    emit(`#${el}=EDGE_LOOP('',(${oriented.map((x) => `#${x}`).join(',')}));`)
    const bound = next()
    emit(`#${bound}=FACE_OUTER_BOUND('',#${el},.T.);`)
    const af = next()
    emit(`#${af}=ADVANCED_FACE('',(#${bound}),#${plane},.T.);`)
    faceIds.push(af)
  }

  const shell = next()
  emit(`#${shell}=CLOSED_SHELL('',(${faceIds.map((f) => `#${f}`).join(',')}));`)
  const brep = next()
  emit(`#${brep}=MANIFOLD_SOLID_BREP('',#${shell});`)

  // AP214 上下文
  const appCtx = next()
  emit(`#${appCtx}=APPLICATION_CONTEXT('configuration controlled 3d designs of mechanical parts and assemblies');`)
  const apd = next()
  emit(`#${apd}=APPLICATION_PROTOCOL_DEFINITION('international standard','config_control_design',1994,#${appCtx});`)
  const prod = next()
  emit(`#${prod}=PRODUCT('box','box','',(#${appCtx}));`)
  const pdf = next()
  emit(`#${pdf}=PRODUCT_DEFINITION_FORMATION('','',#${prod});`)
  const pdef = next()
  emit(`#${pdef}=PRODUCT_DEFINITION('design','',#${pdf},#${appCtx});`)
  const pdShape = next()
  emit(`#${pdShape}=PRODUCT_DEFINITION_SHAPE('','',#${pdef});`)
  const lunit = next()
  emit(`#${lunit}=(LENGTH_UNIT()NAMED_UNIT(*)SI_UNIT(.MILLI.,.METRE.));`)
  const aunit = next()
  emit(`#${aunit}=(NAMED_UNIT(*)PLANE_ANGLE_UNIT()SI_UNIT($,.RADIAN.));`)
  const sunit = next()
  emit(`#${sunit}=(NAMED_UNIT(*)SI_UNIT($,.STERADIAN.)SOLID_ANGLE_UNIT());`)
  const um = next()
  emit(`#${um}=UNCERTAINTY_MEASURE_WITH_UNIT(LENGTH_MEASURE(1.E-5),#${lunit},'','');`)
  const grepc = next()
  emit(`#${grepc}=(GEOMETRIC_REPRESENTATION_CONTEXT(3)GLOBAL_UNCERTAINTY_ASSIGNED_CONTEXT((#${um}))GLOBAL_UNIT_ASSIGNED_CONTEXT((#${lunit},#${aunit},#${sunit}))REPRESENTATION_CONTEXT('',''));`)
  const shapeRep = next()
  emit(`#${shapeRep}=ADVANCED_BREP_SHAPE_REPRESENTATION('box',(#${brep}),#${grepc});`)
  const sdr = next()
  emit(`#${sdr}=SHAPE_DEFINITION_REPRESENTATION(#${pdShape},#${shapeRep});`)

  const data = S.join('\n')
  return `ISO-10303-21;
HEADER;
FILE_DESCRIPTION(('box example'),'2;1');
FILE_NAME('box.step','2024-01-01T00:00:00',(''),(''),'dsh-3d-model-viewer','dsh-3d-model-viewer','');
FILE_SCHEMA(('CONFIG_CONTROL_DESIGN'));
ENDSEC;
DATA;
${data}
ENDSEC;
END-ISO-10303-21;
`
}

// ─────────────────────────────────────────────────────────────────────────────
writeFileSync(join(examples, 'gear.obj'), generateGearObj())
writeFileSync(join(examples, 'torus.stl'), generateTorusStl())
writeFileSync(join(examples, 'box.step'), generateBoxStep())
console.log('generated examples/gear.obj, examples/torus.stl, examples/box.step')
